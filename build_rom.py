def make_header(title=b"SNAKE", code=b"SNAK", maker=b"01"):
    h = bytearray(0xC0)
    h[0x00:0x04] = struct.pack('<I', 0xEA00002E)   # b 0x080000C0
    h[0x04:0x9C + 4] = NINTENDO_LOGO                # 156 bytes
    h[0xA0:0xAC] = title.ljust(12, b'\x00')[:12]
    h[0xAC:0xB0] = code.ljust(4, b'\x00')[:4]
    h[0xB0:0xB2] = maker.ljust(2, b'\x00')[:2]
    h[0xB2] = 0x96          # fixed
    h[0xB3] = 0x00          # main unit code
    h[0xB4] = 0x00          # device type
    h[0xBC] = 0x00          # software version
    chk = 0
    for b in h[0xA0:0xBD]:
        chk -= b
    h[0xBD] = (chk - 0x19) & 0xFF
    return bytes(h)


# ----------------------------------------------------------------------------
# Tiny ARMv4T assembler (only the instructions this game needs)
# ----------------------------------------------------------------------------
def rol32(v, r):
    v &= 0xFFFFFFFF
    r &= 31
    if r == 0:
        return v
    return ((v << r) | (v >> (32 - r))) & 0xFFFFFFFF


COND_CODES = {'eq': 0, 'ne': 1, 'cs': 2, 'cc': 3, 'mi': 4, 'pl': 5, 'vs': 6,
              'vc': 7, 'hi': 8, 'ls': 9, 'ge': 10, 'lt': 11, 'gt': 12,
              'le': 13, 'al': 14}


def cc(cond):
    return COND_CODES[cond] if isinstance(cond, str) else cond


class Table:
    """Blob of data placed after the code; its address is resolved at the end."""
    def __init__(self, data):
        self.data = bytes(data)
        self.addr = None


class Asm:
    def __init__(self, base):
        self.base = base
        self.buf = bytearray()
        self.labels = {}
        self.fixups = []      # (pos, target, cond, link)
        self.lit_uses = []    # (pos, value)
        self.lit_keys = []
        self.lit_index = {}

    # -- helpers -------------------------------------------------------------
    def here(self):
        return self.base + len(self.buf)

    def emit(self, w):
        self.buf += struct.pack('<I', w & 0xFFFFFFFF)

    def label(self, name):
        if name in self.labels:
            raise RuntimeError("duplicate label " + name)
        self.labels[name] = self.here()

    @staticmethod
    def op2_imm(v):
        v &= 0xFFFFFFFF
        for rot in range(16):
            imm8 = rol32(v, 2 * rot)
            if imm8 <= 0xFF:
                return (rot << 8) | imm8
        return None

    def b(self, target, cond=14):
        self.fixups.append((len(self.buf), target, cc(cond), 0))
        self.emit(0)

    def bl(self, target):
        self.fixups.append((len(self.buf), target, 14, 1))
        self.emit(0)

    def ldr_lit(self, rd, value, cond=14):
        cond = cc(cond)
        if value not in self.lit_index:
            self.lit_index[value] = len(self.lit_keys)
            self.lit_keys.append(value)
        self.lit_uses.append((len(self.buf), value))
        self.emit((cond << 28) | 0x059F0000 | (rd << 12))

    def push(self, mask):
        self.emit(0xE92D0000 | mask)

    def pop(self, mask):
        self.emit(0xE8BD0000 | mask)

    def ret(self):
        self.emit(0xE1A0F00E)          # mov pc, lr

    # -- data processing -----------------------------------------------------
    def _dp(self, op, rd, rn, op2, cond=14, s=0, imm=False):
        cond = cc(cond)
        self.emit((cond << 28) | (0x02000000 if imm else 0) |
                  (op << 21) | (s << 20) |
                  (rn << 16) | (rd << 12) | op2)

    def mov_i(self, rd, v, cond=14):
        cond = cc(cond)
        o = self.op2_imm(v)
        if o is None:
            if cond != 14:
                raise RuntimeError("cond mov with big imm")
            self.ldr_lit(rd, v)
        else:
            self._dp(0xD, rd, 0, o, cond, imm=True)

    def mvn_i(self, rd, v, cond=14):
        # v is the resulting value:  MVN rd, #imm  ->  rd = ~imm
        o = self.op2_imm((~v) & 0xFFFFFFFF)
        if o is None:
            raise RuntimeError("mvn imm not encodable: %x" % (v & 0xFFFFFFFF))
        self._dp(0xF, rd, 0, o, cond, imm=True)

    def mvn_r(self, rd, rm, cond=14):
        self._dp(0xF, rd, 0, rm, cond)

    def mov_r(self, rd, rm, cond=14):
        self._dp(0xD, rd, 0, rm, cond)

    def mov_shift(self, rd, rm, typ, amt, cond=14):
        # typ: 0=LSL 1=LSR 2=ASR 3=ROR
        self._dp(0xD, rd, 0, (amt << 7) | (typ << 5) | rm, cond)

    def add_i(self, rd, rn, v, cond=14):
        if v < 0:
            self.sub_i(rd, rn, -v, cond)
            return
        o = self.op2_imm(v)
        if o is None:
            raise RuntimeError("add imm not encodable: %x" % v)
        self._dp(0x4, rd, rn, o, cond, imm=True)

    def subs_i(self, rd, rn, v, cond=14):
        o = self.op2_imm(v)
        if o is None:
            raise RuntimeError('subs imm not encodable: %x' % v)
        self._dp(0x2, rd, rn, o, cond, s=1, imm=True)

    def sub_i(self, rd, rn, v, cond=14):
        if v < 0:
            self.add_i(rd, rn, -v, cond)
            return
        o = self.op2_imm(v)
        if o is None:
            raise RuntimeError("sub imm not encodable: %x" % v)
        self._dp(0x2, rd, rn, o, cond, imm=True)

    def and_i(self, rd, rn, v, cond=14):
        o = self.op2_imm(v)
        if o is None:
            raise RuntimeError("and imm not encodable: %x" % v)
        self._dp(0x0, rd, rn, o, cond, imm=True)

    def add_r(self, rd, rn, rm, cond=14):
        self._dp(0x4, rd, rn, rm, cond)

    def sub_r(self, rd, rn, rm, cond=14):
        self._dp(0x2, rd, rn, rm, cond)

    def cmp_r(self, rn, rm, cond=14):
        self._dp(0xA, 0, rn, rm, cond, s=1)

    def cmp_i(self, rn, v, cond=14):
        o = self.op2_imm(v)
        if o is None:
            raise RuntimeError("cmp imm not encodable: %x" % v)
        self._dp(0xA, 0, rn, o, cond, s=1, imm=True)

    def tst_i(self, rn, v, cond=14):
        o = self.op2_imm(v)
        if o is None:
            raise RuntimeError("tst imm not encodable: %x" % v)
        self._dp(0x8, 0, rn, o, cond, s=1, imm=True)

    def mul(self, rd, rm, rs, cond=14):
        cond = cc(cond)
        self.emit((cond << 28) | (rd << 16) | (rs << 8) | 0x90 | rm)

    # -- loads / stores ------------------------------------------------------
    def _ls(self, base, rd, rn, off, cond=14, post=False):
        cond = cc(cond)
        assert -4096 < off < 4096
        P = 0 if post else 1
        U = 1 if off >= 0 else 0
        W = 0   # for word/byte transfers P=0 already means post-indexed
        self.emit((cond << 28) | base | (P << 24) | (U << 23) | (W << 21) |
                  (rn << 16) | (rd << 12) | abs(off))

    def ldr(self, rd, rn, off=0, cond=14, post=False):
        self._ls(0x04100000, rd, rn, off, cond, post)

    def str(self, rd, rn, off=0, cond=14, post=False):
        self._ls(0x04000000, rd, rn, off, cond, post)

    def ldrb(self, rd, rn, off=0, cond=14, post=False):
        self._ls(0x04500000, rd, rn, off, cond, post)

    def strb(self, rd, rn, off=0, cond=14, post=False):
        self._ls(0x04400000, rd, rn, off, cond, post)

    def _ls_half(self, rd, rn, off, cond=14, post=False, load=False):
        cond = cc(cond)
        assert 0 <= off < 256
        P = 0 if post else 1
        W = 1 if post else 0
        self.emit((cond << 28) | 0x00400000 | (P << 24) | (1 << 23) |
                  (W << 21) | (1 if load else 0) << 20 | (rn << 16) |
                  (rd << 12) | ((off & 0xF0) << 4) | 0xB0 | (off & 0x0F))

    def ldrh(self, rd, rn, off=0, cond=14):
        self._ls_half(rd, rn, off, cond, load=True)

    def strh(self, rd, rn, off=0, cond=14, post=False):
        self._ls_half(rd, rn, off, cond, post=post)

    def _reg_ls(self, base, rd, rn, rm, shift=0, typ=0, cond=14):
        cond = cc(cond)
        self.emit((cond << 28) | base | 0x01000000 | 0x00800000 |
                  (rn << 16) | (rd << 12) | (shift << 7) | (typ << 5) | rm)

    def ldr_r(self, rd, rn, rm, shift=0, cond=14):
        self._reg_ls(0x06100000, rd, rn, rm, shift, 0, cond)

    def str_r(self, rd, rn, rm, shift=0, cond=14):
        self._reg_ls(0x06000000, rd, rn, rm, shift, 0, cond)

    def ldrb_r(self, rd, rn, rm, cond=14):
        self._reg_ls(0x06500000, rd, rn, rm, 0, 0, cond)

    def strb_r(self, rd, rn, rm, cond=14):
        self._reg_ls(0x06400000, rd, rn, rm, 0, 0, cond)

    # -- finalize ------------------------------------------------------------
    def finish(self):
        while len(self.buf) % 4:
            self.buf.append(0)

        for pos, tgt, cond, link in self.fixups:
            target = self.labels[tgt] if isinstance(tgt, str) else tgt
            off = (target - (self.base + pos + 8)) >> 2
            if not (-0x800000 <= off < 0x800000):
                raise RuntimeError("branch out of range")
            w = (cond << 28) | (0x0B000000 if link else 0x0A000000) | (off & 0xFFFFFF)
            struct.pack_into('<I', self.buf, pos, w)

        pool_addr = self.base + len(self.buf)
        for pos, val in self.lit_uses:
            off = pool_addr + 4 * self.lit_index[val] - (self.base + pos + 8)
            if not (0 <= off < 4096):
                raise RuntimeError("literal pool out of range (%d)" % off)
            w = struct.unpack_from('<I', self.buf, pos)[0] | off
            struct.pack_into('<I', self.buf, pos, w)

        addr = pool_addr + 4 * len(self.lit_keys)
        pool = bytearray()
        for val in self.lit_keys:
            if isinstance(val, Table):
                val.addr = addr
                addr += len(val.data)
                addr = (addr + 3) & ~3
                pool += struct.pack('<I', val.addr)
            else:
                pool += struct.pack('<I', val & 0xFFFFFFFF)

        data = bytearray()
        for val in self.lit_keys:
            if isinstance(val, Table):
                while len(data) < val.addr - (pool_addr + 4 * len(self.lit_keys)):
                    data.append(0)
                data += val.data

        return bytes(self.buf), bytes(pool), bytes(data)


