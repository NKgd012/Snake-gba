FONT_ORDER = '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ '


def font_data():
    out = bytearray()
    for ch in FONT_ORDER:
        for row in FONT_ART[ch]:
            bits = 0
            for i, c in enumerate(row):     # i = 0 is the leftmost pixel
                if c == '#':
                    bits |= 1 << i
            out.append(bits)
    return bytes(out)


def cell_table_data():
    out = bytearray()
    for y in range(18):
        for x in range(30):
            out += struct.pack('<I', 0x06000000 + ((16 + y * 8) * 240 + x * 8) * 2)
    return bytes(out)


# EWRAM layout
V_OCC = 0x02000000       # 540 bytes, 0 = free, 1 = snake
V_BUF = 0x02000400       # 540 words, circular body buffer (cell indices)
V_FOOD = 0x02001000
V_SCORE = 0x02001004
V_RAND = 0x02001008
V_PENDX = 0x0200100C
V_PENDY = 0x02001010
V_COUNT = 0x02001014
V_INTERVAL = 0x02001018
V_STATE = 0x0200101C
V_EATEN = 0x02001020
V_NIDX = 0x02001024

# colours (BGR555)
C_BG = 0x0000
C_HUD = 0x0421
C_SNAKE = 0x07E0
C_FOOD = 0x001F
C_TEXT = 0x7FFF
C_LINE = 0x0BE0
C_DIE = 0x03FF


def build():
    a = Asm(CODE_BASE)

    tab_cells = Table(cell_table_data())
    tab_font = Table(font_data())
    tab_score = Table(b'SCORE\x00')
    tab_over = Table(b'GAME OVER\x00')
    tab_press = Table(b'PRESS START\x00')
    tab_title = Table(b'SNAKE\x00')
    tab_hint = Table(b'D PAD MOVE\x00')
    tab_ready = Table(b'READY\x00')

    # ======================================================================
    # entry: display init + static screen
    # ======================================================================
    a.label('start')
    a.ldr_lit(13, 0x03007F00)          # sp (in case the BIOS did not set it)
    a.mov_i(12, 0x04000000)            # r12 = IO base
    a.mov_i(11, 0x06000000)            # r11 = VRAM base
    a.ldr_lit(0, 0x0403)               # mode 3 + BG2 on
    a.strh(0, 12, 0)                   # DISPCNT

    # clear the whole framebuffer to C_BG
    a.mov_i(0, 0x06000000)
    a.mov_i(1, C_BG)
    a.ldr_lit(2, 240 * 160)
    a.label('l_cls')
    a.strh(1, 0, 2, post=True)
    a.subs_i(2, 2, 1)
    a.b('l_cls', 'ne')

    # HUD strip
    a.mov_i(0, 0x06000000)
    a.mov_i(1, 240)
    a.mov_i(2, 16)
    a.ldr_lit(3, C_HUD)
    a.bl('fill_rect')

    # separator line under the HUD
    a.ldr_lit(0, 0x06000000 + 15 * 480)
    a.mov_i(1, 240)
    a.mov_i(2, 1)
    a.ldr_lit(3, C_LINE)
    a.bl('fill_rect')

    # static "SCORE" label
    a.ldr_lit(0, tab_score)
    a.mov_i(1, 4)
    a.mov_i(2, 4)
    a.ldr_lit(3, C_TEXT)
    a.bl('draw_text')

    a.bl('reset_game')

    # title screen: show the name, wait for START
    a.bl('draw_title')
    a.ldr_lit(0, V_STATE)
    a.mov_i(1, 2)
    a.str(1, 0, 0)

    # ======================================================================
    # main loop (one iteration == one video frame)
    # ======================================================================
    a.label('l_main')
    a.bl('wait_vblank')
    a.bl('read_keys')

    a.ldr_lit(0, V_COUNT)
    a.ldr(1, 0, 0)
    a.add_i(1, 1, 1)
    a.str(1, 0, 0)

    a.ldr_lit(0, V_STATE)
    a.ldr(0, 0, 0)
    a.cmp_i(0, 2)
    a.b('l_title', 'eq')
    a.cmp_i(0, 3)
    a.b('l_ready', 'eq')
    a.cmp_i(0, 0)
    a.b('l_dead', 'ne')

    a.ldr_lit(0, V_INTERVAL)
    a.ldr(0, 0, 0)
    a.cmp_r(1, 0)
    a.b('l_main', 'lt')

    a.ldr_lit(0, V_COUNT)
    a.mov_i(1, 0)
    a.str(1, 0, 0)
    a.bl('step')
    a.b('l_main')

    a.label('l_dead')
    a.ldr(0, 12, 0x130)               # KEYINPUT
    a.tst_i(0, 8)                     # START
    a.b('l_main', 'ne')
    a.bl('reset_game')
    a.bl('draw_ready')
    a.ldr_lit(0, V_STATE)
    a.mov_i(1, 3)
    a.str(1, 0, 0)
    a.b('l_main')

    # ======================================================================
    # title screen: wait for START, then begin
    # ======================================================================
    a.label('l_title')
    a.ldr(0, 12, 0x130)               # KEYINPUT
    a.tst_i(0, 8)                     # START
    a.b('l_main', 'ne')               # not pressed yet
    a.bl('reset_game')                # fresh board (state = 0)
    a.bl('draw_ready')
    a.ldr_lit(0, V_STATE)
    a.mov_i(1, 3)
    a.str(1, 0, 0)
    a.b('l_main')

    # ======================================================================
    # ready: board is drawn but the snake only moves once a direction is
    # pressed, so the player never dies before touching the D-pad
    # ======================================================================
    a.label('l_ready')
    a.ldr(0, 12, 0x130)               # KEYINPUT
    a.mvn_r(0, 0)
    a.and_i(0, 0, 0x3F0)              # any direction?
    a.cmp_i(0, 0)
    a.b('l_main', 'eq')               # still waiting
    a.bl('clear_ready')
    a.ldr_lit(0, V_STATE)
    a.mov_i(1, 0)
    a.str(1, 0, 0)
    a.b('l_main')

    # ======================================================================
    # wait_vblank: spin until VCOUNT == 160
    # ======================================================================
    a.label('wait_vblank')
    # phase 1: leave the current vblank period (vcount < 160)
    a.ldr_lit(1, 0x10000)
    a.label('wv_low')
    a.ldrh(0, 12, 6)                  # VCOUNT (16-bit register)
    a.cmp_i(0, 160)
    a.b('wv_active', 'lt')            # active display -> phase 2
    a.subs_i(1, 1, 1)
    a.b('wv_low', 'ne')               # timeout -> carry on anyway
    # phase 2: wait for the next vblank to start (vcount reaches 160)
    a.label('wv_active')
    a.ldr_lit(1, 0x10000)
    a.label('wv_high')
    a.ldrh(0, 12, 6)
    a.cmp_i(0, 160)
    a.b('wv_done', 'ge')
    a.subs_i(1, 1, 1)
    a.b('wv_high', 'ne')
    a.label('wv_done')
    a.ret()

    # ======================================================================
    # read_keys: buffer a direction change for the next game step
    # ======================================================================
    a.label('read_keys')
    a.ldr(0, 12, 0x130)               # KEYINPUT (active low)
    a.mvn_r(0, 0)
    a.and_i(0, 0, 0x3F0)              # keep D-pad bits only

    a.cmp_i(6, 0)                     # moving horizontally?
    a.b('rk_vert', 'eq')

    a.tst_i(0, 0x40)                  # UP
    a.b('rk_up', 'ne')
    a.tst_i(0, 0x80)                  # DOWN
    a.b('rk_down', 'ne')
    a.ret()

    a.label('rk_up')
    a.ldr_lit(1, V_PENDX)
    a.mov_i(2, 0)
    a.str(2, 1, 0)
    a.ldr_lit(1, V_PENDY)
    a.mvn_i(2, -1)                     # -1
    a.str(2, 1, 0)
    a.ret()

    a.label('rk_down')
    a.ldr_lit(1, V_PENDX)
    a.mov_i(2, 0)
    a.str(2, 1, 0)
    a.ldr_lit(1, V_PENDY)
    a.mov_i(2, 1)
    a.str(2, 1, 0)
    a.ret()

    a.label('rk_vert')
    a.tst_i(0, 0x10)                  # RIGHT
    a.b('rk_right', 'ne')
    a.tst_i(0, 0x20)                  # LEFT
    a.b('rk_left', 'ne')
    a.ret()

    a.label('rk_right')
    a.ldr_lit(1, V_PENDX)
    a.mov_i(2, 1)
    a.str(2, 1, 0)
    a.ldr_lit(1, V_PENDY)
    a.mov_i(2, 0)
    a.str(2, 1, 0)
    a.ret()

    a.label('rk_left')
    a.ldr_lit(1, V_PENDX)
    a.mvn_i(2, -1)
    a.str(2, 1, 0)
    a.ldr_lit(1, V_PENDY)
    a.mov_i(2, 0)
    a.str(2, 1, 0)
    a.ret()

    # ======================================================================
    # step: one move of the snake
    #   r4=head x  r5=head y  r6=dir x  r7=dir y
    #   r8=length r9=tailpos r10=headpos
    # ======================================================================
    a.label('step')
    a.push(0x4000)                    # {lr} - step() calls other routines
    a.ldr_lit(0, V_PENDX)
    a.ldr(6, 0, 0)
    a.ldr_lit(0, V_PENDY)
    a.ldr(7, 0, 0)

    a.add_r(1, 4, 6)                  # r1 = new x
    a.add_r(2, 5, 7)                  # r2 = new y

    a.cmp_i(1, 0)
    a.b('l_die', 'lt')
    a.cmp_i(1, 30)
    a.b('l_die', 'ge')
    a.cmp_i(2, 0)
    a.b('l_die', 'lt')
    a.cmp_i(2, 18)
    a.b('l_die', 'ge')

    a.mov_i(0, 30)
    a.mul(3, 2, 0)                    # r3 = newy * 30
    a.add_r(3, 3, 1)                  # r3 = cell index

    a.mov_r(4, 1)
    a.mov_r(5, 2)

    a.ldr_lit(0, V_OCC)
    a.ldrb_r(1, 0, 3)
    a.cmp_i(1, 0)
    a.b('l_die', 'ne')                # ran into itself

    a.ldr_lit(0, V_NIDX)
    a.str(3, 0, 0)

    a.ldr_lit(0, V_FOOD)
    a.ldr(1, 0, 0)
    a.cmp_r(3, 1)
    a.b('l_eat', 'eq')

    # --- normal move: erase the tail cell -------------------------------
    a.ldr_lit(0, V_BUF)
    a.ldr_r(1, 0, 9, shift=2)         # buf[tailpos]
    a.mov_r(0, 1)
    a.mov_i(1, C_BG)
    a.bl('fill_cell')

    a.ldr_lit(0, V_OCC)
    a.ldr_lit(1, V_BUF)
    a.ldr_r(1, 1, 9, shift=2)
    a.mov_i(2, 0)
    a.strb_r(2, 0, 1)

    a.add_i(9, 9, 1)
    a.cmp_i(9, 540)
    a.mov_i(9, 0, cond=0)             # moveq r9, #0
    a.b('l_after_move')

    # --- ate food: grow, score, maybe speed up --------------------------
    a.label('l_eat')
    a.add_i(8, 8, 1)
    a.ldr_lit(0, V_SCORE)
    a.ldr(1, 0, 0)
    a.add_i(1, 1, 1)
    a.str(1, 0, 0)
    a.bl('draw_score')

    a.ldr_lit(0, V_EATEN)
    a.ldr(1, 0, 0)
    a.add_i(1, 1, 1)
    a.str(1, 0, 0)
    a.cmp_i(1, 5)
    a.b('l_spawn', 'lt')
    a.mov_i(1, 0)
    a.str(1, 0, 0)
    a.ldr_lit(0, V_INTERVAL)
    a.ldr(1, 0, 0)
    a.cmp_i(1, 8)
    a.b('l_spawn', 'le')
    a.sub_i(1, 1, 1)
    a.str(1, 0, 0)

    a.label('l_spawn')
    a.bl('spawn_food')

    # --- store / draw the new head --------------------------------------
    a.label('l_after_move')
    a.add_i(10, 10, 1)
    a.cmp_i(10, 540)
    a.mov_i(10, 0, cond=0)            # moveq r10, #0

    a.ldr_lit(0, V_BUF)
    a.ldr_lit(1, V_NIDX)
    a.ldr(2, 1, 0)
    a.str_r(2, 0, 10, shift=2)

    a.ldr_lit(0, V_OCC)
    a.ldr_lit(1, V_NIDX)
    a.ldr(2, 1, 0)
    a.mov_i(3, 1)
    a.strb_r(3, 0, 2)

    a.ldr_lit(0, V_NIDX)
    a.ldr(0, 0, 0)
    a.ldr_lit(1, C_SNAKE)
    a.bl('fill_cell')

    a.ldr_lit(0, V_PENDX)
    a.str(6, 0, 0)
    a.ldr_lit(0, V_PENDY)
    a.str(7, 0, 0)
    a.pop(0x8000)                     # {pc}

    # ======================================================================
    # game over
    # ======================================================================
    a.label('l_die')
    a.ldr_lit(0, V_STATE)
    a.mov_i(1, 1)
    a.str(1, 0, 0)

    a.ldr_lit(0, 0x06000000 + (64 * 240 + 56) * 2)
    a.mov_i(1, 128)
    a.mov_i(2, 46)
    a.mov_i(3, C_BG)
    a.bl('fill_rect')

    a.ldr_lit(0, tab_over)
    a.mov_i(1, 84)
    a.mov_i(2, 72)
    a.ldr_lit(3, C_DIE)
    a.bl('draw_text')

    a.ldr_lit(0, tab_press)
    a.mov_i(1, 76)
    a.mov_i(2, 92)
    a.ldr_lit(3, C_TEXT)
    a.bl('draw_text')
    # step() pushed lr before branching here, so unwind it
    a.pop(0x8000)

    # ======================================================================
    # spawn_food: pick a free cell, paint it
    # ======================================================================
    a.label('spawn_food')
    a.push(0x4010)                    # {r4, lr}
    a.ldr_lit(0, V_RAND)
    a.ldr(1, 0, 0)
    a.ldr_lit(2, 1103515245)
    a.mul(1, 1, 2)
    a.ldr_lit(2, 12345)
    a.add_r(1, 1, 2)
    a.str(1, 0, 0)

    a.mov_shift(1, 1, 0, 16)          # keep low 16 bits
    a.mov_shift(1, 1, 1, 16)
    a.mov_i(2, 540)
    a.mul(1, 1, 2)                    # 0..539 (x*540>>16)
    a.mov_shift(1, 1, 1, 16)
    a.mov_i(4, 540)
    a.ldr_lit(0, V_OCC)

    a.label('sf_loop')
    a.ldrb_r(2, 0, 1)
    a.cmp_i(2, 0)
    a.b('sf_next', 'ne')
    a.ldr_lit(2, V_NIDX)              # never spawn on the fresh head cell
    a.ldr(2, 2, 0)
    a.cmp_r(1, 2)
    a.b('sf_found', 'ne')
    a.label('sf_next')
    a.add_i(1, 1, 1)
    a.cmp_i(1, 540)
    a.mov_i(1, 0, cond=0)
    a.subs_i(4, 4, 1)
    a.b('sf_loop', 'ne')

    a.label('sf_found')
    a.ldr_lit(0, V_FOOD)
    a.str(1, 0, 0)
    a.mov_r(0, 1)
    a.ldr_lit(1, C_FOOD)
    a.bl('fill_cell')
    a.pop(0x8010)                     # {r4, pc}

    # ======================================================================
    # draw_score: repaint the 3 digit score
    # ======================================================================
    a.label('draw_score')
    a.push(0x4000)                    # {lr}
    a.ldr_lit(0, 0x06000000 + (4 * 240 + 192) * 2)
    a.mov_i(1, 48)
    a.mov_i(2, 12)
    a.ldr_lit(3, C_HUD)
    a.bl('fill_rect')
    a.ldr_lit(0, V_SCORE)
    a.ldr(0, 0, 0)
    a.mov_i(1, 200)
    a.mov_i(2, 4)
    a.ldr_lit(3, C_TEXT)
    a.bl('draw_number')
    a.pop(0x8000)

    # ======================================================================
    # fill_rect(addr r0, width r1, height r2, colour r3)
    # ======================================================================
    a.label('fill_rect')
    a.push(0x4030)                    # {r4, r5, lr}
    a.mov_r(4, 2)
    a.label('fr_row')
    a.mov_r(5, 1)
    a.mov_r(2, 0)
    a.label('fr_px')
    a.strh(3, 2, 2, post=True)
    a.subs_i(5, 5, 1)
    a.b('fr_px', 'ne')
    a.add_i(0, 0, 480)
    a.subs_i(4, 4, 1)
    a.b('fr_row', 'ne')
    a.pop(0x8030)                     # {r4, r5, pc}

    # ======================================================================
    # fill_cell(cell index r0, colour r1)  - 8x8 pixels
    # ======================================================================
    a.label('fill_cell')
    a.push(0x4000)
    a.ldr_lit(2, tab_cells)
    a.ldr_r(0, 2, 0, shift=2)
    a.mov_i(2, 8)
    a.label('fc_row')
    a.mov_i(3, 8)
    a.label('fc_px')
    a.strh(1, 0, 2, post=True)
    a.subs_i(3, 3, 1)
    a.b('fc_px', 'ne')
    a.add_i(0, 0, 480)
    a.sub_i(0, 0, 16)
    a.subs_i(2, 2, 1)
    a.b('fc_row', 'ne')
    a.pop(0x8000)

    # ======================================================================
    # draw_char(char r0, x r1, y r2, colour r3)  - 3x5 font at 2x
    # ======================================================================
    a.label('draw_char')
    a.push(0x4FF0)                    # {r4-r11, lr}
    a.cmp_i(0, 0x20)
    a.b('dc_blank', 'eq')
    a.sub_i(0, 0, 0x30)               # '0'
    a.cmp_i(0, 10)
    a.b('dc_idx', 'lt')
    a.sub_i(0, 0, 7)                  # 'A' -> 10
    a.cmp_i(0, 36)
    a.b('dc_idx', 'lt')
    a.label('dc_blank')
    a.mov_i(0, 36)

    a.label('dc_idx')
    a.ldr_lit(4, tab_font)
    a.mov_i(5, 5)
    a.mul(6, 0, 5)
    a.add_r(4, 4, 6)                  # glyph pointer

    a.mov_i(5, 240)
    a.mul(6, 2, 5)
    a.add_r(6, 6, 1)
    a.add_r(6, 6, 6)                  # (y*240 + x) * 2
    a.add_r(6, 6, 11)                 # + VRAM

    a.mov_i(7, 0)                     # row
    a.label('dc_row')
    a.ldrb_r(8, 4, 7)
    a.mov_i(9, 960)
    a.mul(9, 7, 9)
    a.add_r(9, 9, 6)
    a.mov_i(10, 0)                    # column
    a.label('dc_col')
    a.tst_i(8, 1)
    a.b('dc_skip', 'eq')
    a.add_i(0, 9, 480)
    a.strh(3, 9, 0)
    a.strh(3, 9, 2)
    a.strh(3, 0, 0)
    a.strh(3, 0, 2)
    a.label('dc_skip')
    a.add_i(9, 9, 4)
    a.mov_shift(8, 8, 1, 1)
    a.add_i(10, 10, 1)
    a.cmp_i(10, 3)
    a.b('dc_col', 'lt')
    a.add_i(7, 7, 1)
    a.cmp_i(7, 5)
    a.b('dc_row', 'lt')
    a.pop(0x8FF0)                     # {r4-r11, pc}

    # ======================================================================
    # draw_text(string r0, x r1, y r2, colour r3)
    # ======================================================================
    a.label('draw_text')
    a.push(0x40F0)                    # {r4-r7, lr}
    a.mov_r(4, 0)
    a.mov_r(5, 1)
    a.mov_r(6, 2)
    a.mov_r(7, 3)
    a.label('dt_loop')
    a.ldrb(0, 4, 1, post=True)
    a.cmp_i(0, 0)
    a.b('dt_end', 'eq')
    a.mov_r(1, 5)
    a.mov_r(2, 6)
    a.mov_r(3, 7)
    a.bl('draw_char')
    a.add_i(5, 5, 8)
    a.b('dt_loop')
    a.label('dt_end')
    a.pop(0x80F0)

    # ======================================================================
    # draw_number(value r0, x r1, y r2, colour r3) - exactly 3 digits
    # ======================================================================
    a.label('draw_number')
    a.push(0x41F0)                    # {r4-r8, lr}
    a.mov_r(7, 1)
    a.mov_r(8, 2)

    a.mov_i(4, 0)                     # hundreds
    a.label('dn_h')
    a.cmp_i(0, 100)
    a.b('dn_h_done', 'lt')
    a.sub_i(0, 0, 100)
    a.add_i(4, 4, 1)
    a.b('dn_h')
    a.label('dn_h_done')
    a.mov_r(5, 0)
    a.add_i(0, 4, 0x30)
    a.mov_r(1, 7)
    a.mov_r(2, 8)
    a.bl('draw_char')

    a.mov_r(0, 5)
    a.mov_i(4, 0)                     # tens
    a.label('dn_t')
    a.cmp_i(0, 10)
    a.b('dn_t_done', 'lt')
    a.sub_i(0, 0, 10)
    a.add_i(4, 4, 1)
    a.b('dn_t')
    a.label('dn_t_done')
    a.mov_r(6, 0)
    a.add_i(0, 4, 0x30)
    a.add_i(1, 7, 8)
    a.mov_r(2, 8)
    a.bl('draw_char')

    a.add_i(0, 6, 0x30)
    a.add_i(1, 7, 16)
    a.mov_r(2, 8)
    a.bl('draw_char')
    a.pop(0x81F0)

    # ======================================================================
    # draw_title: game name + prompt on an empty board
    # ======================================================================
    a.label('draw_title')
    a.push(0x4000)                    # {lr}
    a.ldr_lit(0, 0x06000000 + 16 * 480)
    a.mov_i(1, 240)
    a.mov_i(2, 144)
    a.mov_i(3, C_BG)
    a.bl('fill_rect')

    a.ldr_lit(0, tab_title)
    a.mov_i(1, 100)
    a.mov_i(2, 56)
    a.ldr_lit(3, C_DIE)
    a.bl('draw_text')

    a.ldr_lit(0, tab_press)
    a.mov_i(1, 76)
    a.mov_i(2, 80)
    a.ldr_lit(3, C_TEXT)
    a.bl('draw_text')

    a.ldr_lit(0, tab_hint)
    a.mov_i(1, 80)
    a.mov_i(2, 104)
    a.ldr_lit(3, C_LINE)
    a.bl('draw_text')
    a.pop(0x8000)

    # ======================================================================
    # draw_ready / clear_ready: "READY" tag in the free part of the HUD
    # ======================================================================
    a.label('draw_ready')
    a.push(0x4000)                    # {lr}
    a.ldr_lit(0, 0x06000000 + 104 * 2)
    a.mov_i(1, 90)
    a.mov_i(2, 16)
    a.mov_i(3, C_HUD)
    a.bl('fill_rect')
    a.ldr_lit(0, tab_ready)
    a.mov_i(1, 108)
    a.mov_i(2, 4)
    a.ldr_lit(3, C_DIE)
    a.bl('draw_text')
    a.pop(0x8000)

    a.label('clear_ready')
    a.push(0x4000)                    # {lr}
    a.ldr_lit(0, 0x06000000 + 104 * 2)
    a.mov_i(1, 90)
    a.mov_i(2, 16)
    a.mov_i(3, C_HUD)
    a.bl('fill_rect')
    a.pop(0x8000)

    # ======================================================================
    # reset_game
    # ======================================================================
    a.label('reset_game')
    a.push(0x4000)                    # {lr}

    # clear the occupancy map
    a.ldr_lit(0, V_OCC)
    a.mov_i(1, 0)
    a.ldr_lit(2, 540)
    a.label('rg_clr')
    a.strb(1, 0, 1, post=True)
    a.subs_i(2, 2, 1)
    a.b('rg_clr', 'ne')

    # clear the play field
    a.ldr_lit(0, 0x06000000 + 16 * 480)
    a.mov_i(1, 240)
    a.mov_i(2, 144)
    a.mov_i(3, C_BG)
    a.bl('fill_rect')

    # snake state: three cells, heading right
    a.mov_i(4, 12)
    a.mov_i(5, 10)
    a.mov_i(6, 1)
    a.mov_i(7, 0)
    a.mov_i(8, 3)
    a.mov_i(9, 0)
    a.mov_i(10, 2)

    a.ldr_lit(0, V_BUF)
    a.mov_i(1, 310)
    a.str(1, 0, 0)
    a.mov_i(1, 311)
    a.str(1, 0, 4)
    a.mov_i(1, 312)
    a.str(1, 0, 8)

    a.ldr_lit(0, V_OCC)
    a.mov_i(1, 1)
    a.mov_i(2, 310)
    a.strb_r(1, 0, 2)
    a.mov_i(2, 311)
    a.strb_r(1, 0, 2)
    a.mov_i(2, 312)
    a.strb_r(1, 0, 2)

    a.mov_i(0, 310)
    a.ldr_lit(1, C_SNAKE)
    a.bl('fill_cell')
    a.mov_i(0, 311)
    a.ldr_lit(1, C_SNAKE)
    a.bl('fill_cell')
    a.mov_i(0, 312)
    a.ldr_lit(1, C_SNAKE)
    a.bl('fill_cell')

    # variables
    a.ldr_lit(0, V_SCORE)
    a.mov_i(1, 0)
    a.str(1, 0, 0)
    a.ldr_lit(0, V_STATE)
    a.str(1, 0, 0)
    a.ldr_lit(0, V_COUNT)
    a.str(1, 0, 0)
    a.ldr_lit(0, V_EATEN)
    a.str(1, 0, 0)
    a.ldr_lit(0, V_INTERVAL)
    a.mov_i(1, 16)
    a.str(1, 0, 0)
    a.ldr_lit(0, V_PENDX)
    a.mov_i(1, 1)
    a.str(1, 0, 0)
    a.ldr_lit(0, V_PENDY)
    a.mov_i(1, 0)
    a.str(1, 0, 0)
    a.ldr_lit(0, V_RAND)
    a.ldr_lit(1, 0x1234ABCD)
    a.str(1, 0, 0)

    a.bl('draw_score')
    a.bl('spawn_food')
    a.pop(0x8000)

    # ======================================================================
    code, pool, data = a.finish()

    rom = bytearray(b'\xFF' * ROM_SIZE)
    header = make_header()
    rom[0:0xC0] = header
    blob = code + pool + data
    if CODE_OFF + len(blob) > ROM_SIZE:
        raise RuntimeError("ROM too small")
    rom[CODE_OFF:CODE_OFF + len(blob)] = blob

    info = {
        'labels': a.labels,
        'code_size': len(code),
        'pool_size': len(pool),
        'data_size': len(data),
        'rom_size': len(rom),
    }
    return bytes(rom), info


